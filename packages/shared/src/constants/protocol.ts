// packages/shared/src/constants/protocol.ts
// IPC 协议版本常量（主进程 ↔ 渲染层契约版本）
// ──────────────────────────────────────────────────────────────
// 用途：
// - 主进程 app:getStatus 返回当前协议版本
// - 渲染层启动时校验：版本不匹配说明主进程/渲染层来自不同构建（如
//   自动更新后单侧先更新），提示用户重启应用，而不是暴露裸 zod 校验错误
//
// 演进规则：
// - 破坏性变更（channel 重命名 / 入参结构不兼容 / 响应结构不兼容）→ 版本 +1
// - 新增 channel / 新增可选字段（向后兼容）→ 版本不变
// ──────────────────────────────────────────────────────────────

/** IPC 协议版本（破坏性变更时递增） */
export const IPC_PROTOCOL_VERSION = 1;
