//! 跨平台支持和通用操作的实用工具模块。
//!
//! 本模块聚合了应用各业务域共享的纯工具函数，避免在 `commands/` 和
//! `bridge/` 中重复实现。所有函数均为无状态纯函数，便于单元测试。
//!
//! ## 子模块
//!
//! - [`paths`]：应用数据目录路径解析与目录创建辅助函数；
//! - [`platform`]：平台检测（macOS/Windows/Linux）与路径规范化的跨平台工具；
//! - [`redact`]：日志、错误消息和 Sentry 事件中的敏感数据脱敏。
//!
//! ## 设计原则
//!
//! - **无 `AppHandle` 依赖优先**：核心逻辑以 `&Path` 等原始参数暴露，
//!   便于在无 Tauri 运行时的环境中测试；
//! - **阻塞/异步分离**：路径解析（`get_app_data_file_path`）可在异步上下文
//!   安全调用，而目录创建（`ensure_dir_exists`）是阻塞操作，调用方
//!   应在 `spawn_blocking` 中执行；
//! - **脱敏统一入口**：所有可能包含敏感数据的输出（日志、错误消息、
//!   Sentry 事件）都应通过 [`redact`] 模块处理，避免敏感数据泄露。

pub mod paths;
pub mod platform;
pub mod redact;
